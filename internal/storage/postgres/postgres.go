package postgres

import (
	"context"
	"errors"
	"fmt"
	"url-shortener/internal/storage"

	"github.com/jackc/pgx/v5"
	"github.com/jackc/pgx/v5/pgconn"
	"github.com/jackc/pgx/v5/pgxpool"
)

const uniqueViolation = "23505"

type Storage struct {
	db *pgxpool.Pool
}

func New(storagePath string) (*Storage, error) {
	const fn = "storage.postgres.New"

	db, err := pgxpool.New(context.Background(), storagePath)
	if err != nil {
		return nil, fmt.Errorf("%s: %w", fn, err)
	}

	_, err = db.Exec(
		context.Background(),
		`CREATE TABLE IF NOT EXISTS url (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			alias TEXT NOT NULL UNIQUE,
			url TEXT NOT NULL,
			created_at TIMESTAMP DEFAULT NOW()
		);
		CREATE INDEX IF NOT EXISTS idx_alias ON url(alias);`,
	)

	if err != nil {
		return nil, fmt.Errorf("%s: %w", fn, err)
	}

	return &Storage{db: db}, nil
}

func (s *Storage) SaveUrl(ctx context.Context, urlToSave string, alias string) (int64, error) {
	const fn = "storage.postgres.SaveUrl"

	var id int64
	err := s.db.QueryRow(
		ctx,
		`INSERT INTO url(alias, url) VALUES($1, $2)
		RETURNING id`,
		alias,
		urlToSave,
	).Scan(&id)

	if err != nil {
		var pgErr *pgconn.PgError
		if errors.As(err, &pgErr) && pgErr.Code == uniqueViolation {
			return 0, fmt.Errorf("%s: %w", fn, storage.ErrUrlExists)
		}
		return 0, fmt.Errorf("%s: %w", fn, err)
	}

	return id, nil
}

func (s *Storage) GetUrl(ctx context.Context, alias string) (string, error) {
	const fn = "storage.postgres.GetUrl"

	var url string
	err := s.db.QueryRow(
		ctx,
		"SELECT url FROM url WHERE alias = $1",
		alias,
	).Scan(&url)

	if err != nil {
		if errors.Is(err, pgx.ErrNoRows) {
			return "", storage.ErrUrlNotFound
		}
		return "", fmt.Errorf("%s: execute statement %w", fn, err)
	}

	return url, nil
}

func (s *Storage) UpdateUrl(ctx context.Context, alias string, newUrl string) (int64, error) {
	const fn = "storage.postgres.UpdateURL"

	result, err := s.db.Exec(
		ctx,
		"UPDATE url SET url = $1 WHERE alias = $2",
		newUrl,
		alias,
	)

	if err != nil {
		return 0, fmt.Errorf("%s: %w", fn, err)
	}

	rowsAffected := result.RowsAffected()
	if rowsAffected == 0 {
		return 0, fmt.Errorf("%s: %w", fn, storage.ErrUrlNotFound)
	}

	return rowsAffected, nil
}

func (s *Storage) DeleteUrl(ctx context.Context, alias string) (int64, error) {
	const fn = "storage.postgres.DeleteURL"

	result, err := s.db.Exec(
		ctx,
		"DELETE FROM url WHERE alias = $1",
		alias,
	)

	if err != nil {
		return 0, fmt.Errorf("%s: execute statement %w", fn, err)
	}

	rowsAffected := result.RowsAffected()

	return rowsAffected, nil
}

func (s *Storage) Close() error {
	s.db.Close()
	return nil
}
